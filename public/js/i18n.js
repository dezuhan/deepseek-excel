  let currentLocale = DEFAULT_LOCALE;

  function resolveLocale(candidate) {
    if (!candidate || typeof candidate !== 'string') return DEFAULT_LOCALE;
    const normalized = candidate.trim().replace('_', '-');
    if (SUPPORTED_LOCALES.includes(normalized)) return normalized;
    const base = normalized.split('-')[0].toLowerCase();
    if (base === 'id' || base === 'in') return 'id-ID';
    if (base === 'en') return 'en-US';
    return DEFAULT_LOCALE;
  }

  /** Initial language: priority ?lang parameter → stored preference → Office language → browser. */
  function detectLocale(options) {
    const opts = options || {};
    if (opts.paramLocale) return resolveLocale(opts.paramLocale);
    if (opts.storedLocale) return resolveLocale(opts.storedLocale);
    if (opts.officeLocale) return resolveLocale(opts.officeLocale);
    if (opts.browserLocale) return resolveLocale(opts.browserLocale);
    return DEFAULT_LOCALE;
  }

  function interpolate(template, params) {
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (match, key) =>
      Object.prototype.hasOwnProperty.call(params, key) && params[key] !== undefined && params[key] !== null
        ? String(params[key])
        : match);
  }

  function translate(locale, key, params) {
    const table = messages[locale] || messages[DEFAULT_LOCALE];
    const fallback = messages[DEFAULT_LOCALE];
    const template = table[key] !== undefined ? table[key] : fallback[key];
    if (template === undefined) return key;
    return interpolate(template, params);
  }

  function t(key, params) {
    return translate(currentLocale, key, params);
  }

  return {
    DEFAULT_LOCALE,
    SUPPORTED_LOCALES,
    messages,
    resolveLocale,
    detectLocale,
    translate,
    t,
    getLocale: () => currentLocale,
    setLocale(locale) {
      currentLocale = resolveLocale(locale);
      return currentLocale;
    },
    /** List of keys missing from a locale (used by the automated tests). */
    missingKeys(locale) {
      const base = Object.keys(messages[DEFAULT_LOCALE]);
      const target = messages[locale] || {};
      return base.filter((key) => target[key] === undefined);
    },
    extraKeys(locale) {
      const base = new Set(Object.keys(messages[DEFAULT_LOCALE]));
      return Object.keys(messages[locale] || {}).filter((key) => !base.has(key));
    },
  };
